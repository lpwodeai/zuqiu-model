def normalize_team_name(raw: str) -> str | None:
    """原始队名（中/英/别名）→ canonical_en（fbref 英文名）。

    两级匹配：canonical_en/别名精确命中优先；否则对每个 canonical_en 的 alias
    列表做子串兜底（中文短简写允许双向，英文仅 name⊆raw 方向，避免通用词误配）。
    """
    if not raw:
        return None
    raw = str(raw).strip()
    rl = raw.lower()
    # 1. 精确命中 canonical_en
    for ce in TEAM_ALIASES:
        if ce.lower() == rl:
            return ce
    # 2. 精确命中别名
    for ce, aliases in TEAM_ALIASES.items():
        for a in aliases:
            if a.lower() == rl:
                return ce
    # 3. 子串兜底（中文短简写双向，英文仅 alias⊆raw）
    has_cn = any('\u4e00' <= c <= '\u9fff' for c in raw)
    for ce, aliases in TEAM_ALIASES.items():
        for a in aliases:
            al = a.lower()
            if not al:
                continue
            if al in rl and not (al.isascii() and len(al) < 4):
                return ce
            if has_cn and rl in al:
                return ce
    return None
